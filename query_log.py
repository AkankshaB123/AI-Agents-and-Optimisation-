def render_page():
    import streamlit as st

    st.set_page_config(page_title="Query Log", page_icon="🗂️", layout="wide")
    st.title("🗂️ Today's Query Log")
    st.caption(
        "One row per result, with its cosine-similarity score. "
        "Rows from previous days are deleted automatically."
    )

    col_a, col_b, _ = st.columns([1, 1, 4])
    with col_a:
        st.button("🔄 Refresh")
    with col_b:
        if st.button("🗑️ Purge previous days"):
            st.toast(f"Deleted {purge_old_records()} old rows")

    only_displayed = st.checkbox("Only results that were displayed (score above threshold)")
    rows = fetch_today(displayed_only=only_displayed)

    if not rows:
        st.info("No queries logged yet today.")
        return

    st.metric("Queries logged today", len({(r["queried_at"], r["user_query"]) for r in rows}))

    table = [
        {
            "Time": r["queried_at"][11:],
            "User query": r["user_query"],
            "Result": r["result_title"] or "(no results)",
            "Brand": r["result_brand"],
            "Price": r["result_price"],
            "Score": r["score"],
            "Passed threshold": bool(r["passed_threshold"]),
            "Displayed": bool(r["displayed"]),
            "URL": r["result_url"],
        }
        for r in rows
    ]
    st.dataframe(table)


def cli():
    parser = argparse.ArgumentParser(description="Manage the daily query log.")
    parser.add_argument("--purge", action="store_true", help="delete rows from previous days")
    parser.add_argument("--show", action="store_true", help="print today's rows")
    args = parser.parse_args()

    if args.purge:
        print(f"Deleted {purge_old_records()} old rows")
    if args.show:
        for r in fetch_today():
            print(
                f"{r['queried_at']} | {r['user_query']} | "
                f"{r['result_title']} | {r['score']} | displayed={r['displayed']}"
            )
    if not (args.purge or args.show):
        parser.print_help()


def _in_streamlit() -> bool:
    try:
        from streamlit.runtime.scriptrunner import get_script_run_ctx

        return get_script_run_ctx() is not None
    except Exception:  # noqa: BLE001
        return False


if __name__ == "__main__":
    if _in_streamlit():
        render_page()
    else:
        cli()