def parse_user_prompt(user_prompt: str):
    """Extracts search constraints: query terms, max price, gender, target brand, and target category."""
    query = user_prompt
    max_price = None
    gender = None
    target_brand = None
    category = None

    # Price parsing
    price_match = re.search(
        r"under\s*\$?(\d+(?:\.\d+)?)", user_prompt, re.IGNORECASE
    )
    if price_match:
        max_price = float(price_match.group(1))
        query = re.sub(
            r"under\s*\$?(\d+(?:\.\d+)?)", "", query, flags=re.IGNORECASE
        ).strip()

    # Gender intent extraction
    if re.search(
        r"\b(women|womens|female|woman|ladies)\b", user_prompt, re.IGNORECASE
    ):
        gender = "female"
    elif re.search(
        r"\b(men|mens|male|man|guys)\b", user_prompt, re.IGNORECASE
    ):
        gender = "male"

    # Category intent extraction
    for cat_key, synonyms in CATEGORY_KEYWORDS.items():
        if any(
            re.search(rf"\b{re.escape(syn)}\b", user_prompt, re.IGNORECASE)
            for syn in synonyms
        ):
            category = cat_key
            break

    # Brand target detection
    for store in POPULAR_SHOPIFY_STORES:
        brand_name = store.split(".")[0].lower()
        if re.search(rf"\b{re.escape(brand_name)}\b", user_prompt, re.IGNORECASE):
            target_brand = store
            break

    return query, max_price, gender, target_brand, category


