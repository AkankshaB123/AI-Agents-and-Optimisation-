def fetch_store_products(
    store: str,
    query: str,
    max_price: float = None,
    gender: str = None,
    category: str = None,
) -> list:
    """Fast single-store worker with strict stock, gender, and category level filtering."""
    headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"}
    api_url = f"https://{store}/search/suggest.json?q={query}&resources[type]=product&resources[limit]=10"
    matched_products = []

    target_keywords = [w.lower() for w in re.findall(r"\b\w{3,}\b", query)]

    try:
        res = session.get(api_url, headers=headers, timeout=1.2)
        if res.status_code != 200:
            return matched_products

        products = (
            res.json()
            .get("resources", {})
            .get("results", {})
            .get("products", [])
        )

        for prod in products:
            # 1. STRICT STOCK CHECK: Only in-stock items allowed
            is_available = prod.get("available", True)
            if not is_available:
                continue

            title = prod.get("title", "")
            price = float(prod.get("price", 0.0))
            title_lower = title.lower()

            # 2. CATEGORY-LEVEL MANDATE FILTERING
            if category:
                allowed_synonyms = CATEGORY_KEYWORDS.get(category, [category])
                # Ensure the product title matches at least one category synonym
                if not any(
                    re.search(rf"\b{re.escape(syn)}\b", title_lower)
                    for syn in allowed_synonyms
                ):
                    continue

                # Exclude cross-category collision keywords
                if category == "t-shirt":
                    forbidden = [
                        "towel",
                        "slipper",
                        "slide",
                        "pant",
                        "short",
                        "sock",
                        "hoodie",
                        "jacket",
                    ]
                    if any(f in title_lower for f in forbidden):
                        continue

            # 3. GENDER FILTERING
            if gender == "female":
                if any(m in title_lower for m in ["men's", "mens", "for men"]):
                    continue
            elif gender == "male":
                if any(
                    w in title_lower
                    for w in ["women's", "womens", "for women"]
                ):
                    continue

            # 4. KEYWORD FILTERING
            if target_keywords and not any(
                kw in title_lower for kw in target_keywords
            ):
                continue

            if max_price and price > max_price:
                continue

            raw_desc = (
                prod.get("body")
                or prod.get("summary")
                or "No description provided."
            )
            clean_desc = re.sub(r"<[^>]+>", "", raw_desc).strip()[:100] + "..."

            image_url = prod.get("image") or prod.get("featured_image", {}).get(
                "src"
            )
            if image_url:
                if image_url.startswith("//"):
                    image_url = f"https:{image_url}"
                elif not image_url.startswith("http"):
                    image_url = f"https://{store}/{image_url.lstrip('/')}"

            raw_url = prod.get("url", "")
            product_url = (
                f"https://{store}{raw_url}"
                if raw_url.startswith("/")
                else raw_url
            )

            matched_products.append(
                {
                    "title": title,
                    "price": f"${price:.2f}",
                    "brand": store,
                    "availability": "In Stock",
                    "description": clean_desc,
                    "url": product_url,
                    "image_url": image_url,
                }
            )
    except Exception:
        pass

    return matched_products


def search_shopify_dynamic(prompt: str = "") -> list:
    """Parallel multi-store search executor enforcing active session intent context."""
    query, max_price, gender, target_brand, category = parse_user_prompt(prompt)

    # Persist intent parameters into session state
    if gender:
        st.session_state.user_intent["gender"] = gender
    else:
        gender = st.session_state.user_intent.get("gender")

    if category:
        st.session_state.user_intent["category"] = category
    else:
        category = st.session_state.user_intent.get("category")

    if target_brand:
        st.session_state.user_intent["brand"] = target_brand

    target_stores = (
        [target_brand]
        if target_brand
        else st.session_state.user_intent.get("brand")
    )
    stores_to_search = (
        [target_stores]
        if isinstance(target_stores, str)
        else POPULAR_SHOPIFY_STORES
    )

    all_matched_products = []

    with ThreadPoolExecutor(max_workers=20) as executor:
        futures = [
            executor.submit(
                fetch_store_products, store, query, max_price, gender, category
            )
            for store in stores_to_search
        ]
        for future in as_completed(futures):
            results = future.result()
            if results:
                all_matched_products.extend(results)

    all_matched_products.sort(key=lambda x: float(x["price"].replace("$", "")))
    unique_brand_products, seen_stores = [], set()

    for item in all_matched_products:
        if item["brand"] not in seen_stores:
            seen_stores.add(item["brand"])
            unique_brand_products.append(item)
            if len(unique_brand_products) == 6:
                break

    return unique_brand_products


